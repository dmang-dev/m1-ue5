"""Generate M1PanelTable.h -- Marathon wall control panels as interactables.

Marathon control panels live in the SIDS chunk (a side with flag 0x2). The
panel_type selects behaviour:

    0 oxygen_refuel   1 shield_refuel    2 double_shield   3 triple_shield
    4 light_switch    5 platform_switch  6 pattern_buffer  7 tag_switch
    8 computer_terminal

v1 emits the clean, high-value interactables:
  * shield rechargers (1/2/3) -> refill shields toward 1x/2x/3x cap on use
  * pattern buffers (6)        -> save the campaign checkpoint on use
  * oxygen rechargers (0)      -> refill suit oxygen to full on use (matters on
                                  vacuum levels, e.g. L08 G4 Sunbathing)
Terminals (8) are already placed by gen_terminal_assets.py; switches (4/5/7)
are follow-ups.

Run:  C:\\m1-ue5\\.venv\\Scripts\\python.exe Tools/gen_panel_assets.py

Position = the panel side's line midpoint in the final imported UE frame
(S=100/1024, X=mx*S, Y=my*S), Z = polygon floor + PANEL_Z.
"""
import glob
import os
import re

import json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPS = os.path.join(ROOT, "Reference", "Maps")
OUT = os.path.join(ROOT, "Source", "M1UE5", "M1PanelTable.h")

S = 100.0 / 1024.0
PANEL_Z = 55.0   # cm above the floor (matches the terminal panel height)

# panel_type -> (Kind, Cap). Kind 0 = shield charger, 1 = pattern buffer,
# 2 = oxygen recharger (Cap = M1Tuning::GPlayerOxygen).
SHIELD_CAP = {1: 150.0, 2: 300.0, 3: 450.0}
BUFFER_TYPES = {6, 13}
OXY_CAP = 100.0


def safe(stem):
    return re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_")


def panels_for_level(data):
    sids = data.get("SIDS") or []
    epnt = data.get("EPNT") or []
    lins = data.get("LINS") or []
    polys = data.get("POLY") or []
    out = []
    for s in sids:
        if not (s.get("flags", 0) & 0x2):
            continue  # not a control panel
        pt = s.get("panel_type", -1)
        if pt in SHIELD_CAP:
            kind, cap = 0, SHIELD_CAP[pt]
        elif pt in BUFFER_TYPES:
            kind, cap = 1, 0.0
        elif pt == 0:
            kind, cap = 2, OXY_CAP  # oxygen recharger
        else:
            continue  # terminal / switch -> handled elsewhere or deferred
        li = s.get("line_index", -1)
        if not (0 <= li < len(lins)):
            continue
        ln = lins[li]
        e1, e2 = ln["endpoint1"], ln["endpoint2"]
        if not (0 <= e1 < len(epnt) and 0 <= e2 < len(epnt)):
            continue
        mx = (epnt[e1]["x"] + epnt[e2]["x"]) / 2.0
        my = (epnt[e1]["y"] + epnt[e2]["y"]) / 2.0
        pi = s.get("poly_index", -1)
        floor = polys[pi]["floor_height"] if 0 <= pi < len(polys) else 0
        out.append({
            "x": round(mx * S, 2),
            "y": round(my * S, 2),
            "z": round(floor * S + PANEL_Z, 2),
            "kind": kind,
            "cap": round(cap, 1),
        })
    return out


def main():
    files = sorted(f for f in glob.glob(os.path.join(MAPS, "*.json"))
                   if not f.endswith("manifest.json"))
    levels = []
    total = chargers = buffers = oxygen = 0
    for f in files:
        d = json.load(open(f, encoding="utf-8"))
        stem = safe(os.path.splitext(os.path.basename(f))[0])
        panels = panels_for_level(d.get("data", {}))
        total += len(panels)
        chargers += sum(1 for p in panels if p["kind"] == 0)
        buffers += sum(1 for p in panels if p["kind"] == 1)
        oxygen += sum(1 for p in panels if p["kind"] == 2)
        levels.append(("L_" + stem, panels))

    lines = [
        "// GENERATED by Tools/gen_panel_assets.py -- do not hand-edit.",
        "// Regenerate with:  python Tools/gen_panel_assets.py",
        "",
        "#pragma once",
        "",
        "#include \"CoreMinimal.h\"",
        "#include \"Containers/ArrayView.h\"",
        "",
        "/** One Marathon wall control panel. Kind: 0 = shield charger (refill to",
        " *  Cap on use), 1 = pattern buffer (save on use), 2 = oxygen recharger",
        " *  (refill suit oxygen to Cap on use). Position in UE cm. */",
        "struct FM1Panel",
        "{",
        "\tfloat X, Y, Z;",
        "\tint32 Kind;",
        "\tfloat Cap;",
        "};",
        "",
        "struct FM1LevelPanels",
        "{",
        "\tconst TCHAR* LevelName;",
        "\tconst FM1Panel* Panels;",
        "\tint32 Count;",
        "};",
        "",
    ]
    for level_name, panels in levels:
        lines.append("static const FM1Panel GM1Panels_%s[] =" % level_name)
        lines.append("{")
        for p in panels:
            lines.append("\t{ %.2ff, %.2ff, %.2ff, %d, %.1ff },"
                         % (p["x"], p["y"], p["z"], p["kind"], p["cap"]))
        if not panels:
            lines.append("\t{ 0.00f, 0.00f, 0.00f, -1, 0.0f },  // none")
        lines.append("};")
        lines.append("")

    lines.append("static const FM1LevelPanels GM1LevelPanelTable[] =")
    lines.append("{")
    for level_name, panels in levels:
        lines.append("\t{ TEXT(\"%s\"), GM1Panels_%s, %d },"
                     % (level_name, level_name, len(panels)))
    lines.append("};")
    lines.append("")
    lines.append("static const int32 GM1LevelPanelTableCount = UE_ARRAY_COUNT(GM1LevelPanelTable);")
    lines.append("")
    lines.append("static TArrayView<const FM1Panel> M1PanelsForLevel(const FString& MapName)")
    lines.append("{")
    lines.append("\tfor (const FM1LevelPanels& Level : GM1LevelPanelTable)")
    lines.append("\t{")
    lines.append("\t\tif (MapName.Contains(Level.LevelName, ESearchCase::IgnoreCase))")
    lines.append("\t\t{")
    lines.append("\t\t\treturn TArrayView<const FM1Panel>(Level.Panels, Level.Count);")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn TArrayView<const FM1Panel>();")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote %s" % OUT)
    print("%d panels across %d levels: %d chargers, %d save buffers, %d oxygen"
          % (total, len(levels), chargers, buffers, oxygen))


if __name__ == "__main__":
    main()
