"""Generate the weapon-in-hand (viewmodel) sprite tables from extracted data.

Canonical sources:
  Reference/Physics/physics.json   weapons[i].collection/idle_shape/firing_shape/
                                   reloading_shape (collection is always 1)
  Reference/Shapes/Coll_01/        shapes.json high_shapes -> low_shapes -> bitmaps

Outputs:
  Reference/Sprites/weapon_import_list.json   png -> T_wpn<i>_<state><frame>
                                              (consumed by ue5_import_sprites.py)
  Source/M1UE5/M1WeaponSpriteTable.h          generated per-weapon frame table

Run with a real Windows python (e.g. UE's ThirdParty python) -- an MSYS python
emits /c/... paths the UE editor cannot open.
"""
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, "Reference")
PHYSICS = os.path.join(REF, "Physics", "physics.json")
COLL1 = os.path.join(REF, "Shapes", "Coll_01")
OUT_LIST = os.path.join(REF, "Sprites", "weapon_import_list.json")
OUT_HEADER = os.path.join(ROOT, "Source", "M1UE5", "M1WeaponSpriteTable.h")

# Cap animation frames per state (fire anims are 1-4 frames in M1 anyway).
MAX_FRAMES = 4


def png_size(path):
    with open(path, "rb") as fh:
        head = fh.read(33)
    if head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        raise ValueError("not a PNG: " + path)
    w, h = struct.unpack(">II", head[16:24])
    return w, h


def main():
    phys = json.load(open(PHYSICS, encoding="utf-8"))
    shapes = json.load(open(os.path.join(COLL1, "shapes.json"), encoding="utf-8"))
    high = shapes["high_shapes"]
    low = shapes["low_shapes"]

    imports = []
    rows = []

    def frames_of(shape_idx, weapon_idx, state):
        """Resolve a high_shape's frame pngs -> (asset stem, count, w, h, fps)."""
        if shape_idx is None or shape_idx < 0 or shape_idx >= len(high):
            return None
        hs = high[shape_idx]
        idxs = hs.get("low_shape_indices") or []
        fpv = hs.get("frames_per_view") or 0
        idxs = idxs[:min(fpv, MAX_FRAMES)] if fpv > 0 else []
        if not idxs:
            return None
        base = "T_wpn%d_%s" % (weapon_idx, state)
        w = h = 0
        count = 0
        for i, li in enumerate(idxs):
            png = os.path.join(COLL1, "bitmaps",
                               "%03d.png" % low[li]["bitmap_index"])
            if not os.path.isfile(png):
                continue
            if count == 0:
                w, h = png_size(png)
            imports.append({"png_path": png, "asset_name": "%s%d" % (base, i)})
            count += 1
        if count == 0:
            return None
        ticks = hs.get("ticks_per_frame") or 10
        return {"base": base, "count": count, "w": w, "h": h,
                "fps": 30.0 / max(1, ticks)}

    for wi, w in enumerate(phys["weapons"]):
        idle = frames_of(w.get("idle_shape"), wi, "idle")
        fire = frames_of(w.get("firing_shape"), wi, "fire")
        reload_ = frames_of(w.get("reloading_shape"), wi, "reload")
        rows.append((wi, idle, fire, reload_))

    os.makedirs(os.path.dirname(OUT_LIST), exist_ok=True)
    json.dump(imports, open(OUT_LIST, "w", encoding="utf-8"), indent=1)

    def cseq(entry):
        if entry is None:
            return 'nullptr, 0, 0.0f, 0, 0'
        return 'TEXT("%s"), %d, %.3ff, %d, %d' % (
            entry["base"], entry["count"], entry["fps"], entry["w"], entry["h"])

    lines = [
        "#pragma once",
        "",
        "// GENERATED by Tools/gen_weapon_sprites.py -- do not edit by hand.",
        "// Weapon-in-hand sprite frames from Shapes.shps collection 1, selected by",
        "// the canonical idle/firing/reloading shape indices in Physics.phys.",
        "// Frame assets live at /Game/Sprites/Weapons/<Base><frame>.",
        "",
        "#include \"CoreMinimal.h\"",
        "",
        "struct FM1WeaponSpriteSeq",
        "{",
        "\tconst TCHAR* Base;   // nullptr = state has no frames (fall back to idle)",
        "\tint32 Frames;",
        "\tfloat Fps;",
        "\tint32 PixelW;        // first frame's PNG size (Marathon 640x480-era art)",
        "\tint32 PixelH;",
        "};",
        "",
        "struct FM1WeaponSpriteRow",
        "{",
        "\tFM1WeaponSpriteSeq Idle;",
        "\tFM1WeaponSpriteSeq Fire;",
        "\tFM1WeaponSpriteSeq Reload;",
        "};",
        "",
        "// Indexed by weapon slot 0..6 (Fist..Alien), same order as the weapon array.",
        "static const FM1WeaponSpriteRow GM1WeaponSprites[] =",
        "{",
    ]
    for wi, idle, fire, reload_ in rows:
        lines.append("\t{ {%s}, {%s}, {%s} }," % (cseq(idle), cseq(fire), cseq(reload_)))
    lines += ["};", ""]
    open(OUT_HEADER, "w", encoding="utf-8", newline="\n").write("\n".join(lines))

    print("weapon sprite imports:", len(imports))
    for wi, idle, fire, reload_ in rows:
        print("  wpn%d idle=%s fire=%s reload=%s" % (
            wi,
            idle and "%d@%dx%d" % (idle["count"], idle["w"], idle["h"]),
            fire and "%df" % fire["count"],
            reload_ and "%df" % reload_["count"]))
    print("wrote:", OUT_LIST)
    print("wrote:", OUT_HEADER)


if __name__ == "__main__":
    main()
