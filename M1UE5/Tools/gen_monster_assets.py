def _safe(stem):
    """UE-safe asset name -- MUST match ue5_headless_build.py::_safe exactly."""
    return re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_")


# ---------------------------------------------------------------------------
# Sound id -> imported UE asset path. Replicates ue5_import_sounds.py naming:
# per family folder (sorted wavs), the first wav mapping to a canonical name
# gets A_<name>; later duplicates get A_<name>_<id>; unmapped ids get A_<id>
# (which we treat as "no sound" -- low confidence names are not worth wiring).

def build_sound_asset_map():
    with open(NAME_MAP_PATH, encoding="utf-8") as fh:
        name_map = json.load(fh)["map"]
    assets = {}  # "01070" -> "/Game/Audio/Monster/A_hunter_activate.A_hunter_activate"
    families = sorted(d for d in os.listdir(SOUNDS)
                      if os.path.isdir(os.path.join(SOUNDS, d)))
    for fam in families:
        dest = "/Game/Audio/" + fam.capitalize()
        used = set()
        for wav in sorted(glob.glob(os.path.join(SOUNDS, fam, "*.wav"))):
            stem = os.path.splitext(os.path.basename(wav))[0]
            canonical = name_map.get(stem)
            if canonical:
                asset = "A_" + canonical
                if asset in used:
                    asset = "A_%s_%s" % (canonical, stem)
                used.add(asset)
                assets[stem] = "%s/%s.%s" % (dest, asset, asset)
            # unmapped wavs import as A_<id>: intentionally NOT exposed here
    return assets


SOUND_ASSETS = build_sound_asset_map()


def sound_path(resource_id):
    if resource_id is None or resource_id < 0:
        return ""
    return SOUND_ASSETS.get("%05d" % resource_id, "")


# ---------------------------------------------------------------------------
# Shapes

_shapes_cache = {}


def load_collection(coll):
    if coll in _shapes_cache:
        return _shapes_cache[coll]
    path = os.path.join(SHAPES, "Coll_%02d" % coll, "shapes.json")
    data = None
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    _shapes_cache[coll] = data
    return data


def resolve_state(coll_data, coll, shape_ref):
    """shape_ref ({'shape': N, ...} or None) -> dict with the FRONT (view 0)
    frame list, or None. Each frame: png path, world box in cm."""
    if not shape_ref:
        return None
    idx = shape_ref.get("shape", -1)
    highs = coll_data["high_shapes"]
    if idx < 0 or idx >= len(highs):
        return None
    hs = highs[idx]
    sounds = [hs.get("key_frame_sound", -1), hs.get("first_frame_sound", -1),
              hs.get("last_frame_sound", -1)]
    fpv = hs["frames_per_view"]
    flat = hs["low_shape_indices"]
    if fpv <= 0 or not flat:
        return None
    frames = []
    for f in range(min(fpv, len(flat))):  # view 0 = first fpv entries (views-major)
        low_idx = flat[f]
        lows = coll_data["low_shapes"]
        if low_idx < 0 or low_idx >= len(lows):
            return None
        low = lows[low_idx]
        png = os.path.join(SHAPES, "Coll_%02d" % coll, "bitmaps",
                           "%03d.png" % low["bitmap_index"])
        if not os.path.isfile(png):
            return None
        frames.append({
            "png": png,
            "bitmap_index": low["bitmap_index"],
            "width_cm": round((low["world_right"] - low["world_left"]) * CM_PER_INTERNAL, 2),
            "height_cm": round((low["world_top"] - low["world_bottom"]) * CM_PER_INTERNAL, 2),
        })
    if not frames:
        return None
    return {
        "shape_index": idx,
        "shape_name": hs.get("name"),
        "ticks_per_frame": hs["ticks_per_frame"],
        "frame_time_s": round(hs["ticks_per_frame"] / TICKS_PER_SECOND, 4),
        # First valid frame sound (key > first > last), as a 'snd ' resource id.
        "frame_sound": next((s for s in sounds if s is not None and s >= 0), -1),
        "frames": frames,
    }


# ---------------------------------------------------------------------------
# Build per-type data

def used_monster_types():
    types = {}
    for f in sorted(glob.glob(os.path.join(GEO, "*_placements.json"))):
        if not re.match(r"^\d{2}_", os.path.basename(f)):
            continue  # debug rooms / look variants are not cooked
        with open(f, encoding="utf-8") as fh:
            d = json.load(fh)
        for o in d["objects"]:
            if o["type"] == 0:
                types[o["object_index"]] = types.get(o["object_index"], 0) + 1
    return types


def attack_info(monster, projectiles):
    """(range_cm, damage, ranged?, ranged_speed_cms) preferring melee, else
    ranged, per the v1 design. Damage = projectile base + random/2."""
    def proj_damage(a):
        p = projectiles[a["type"]]
        return p["damage"]["base"] + p["damage"]["random"] / 2.0

    melee = monster.get("melee_attack")
    ranged = monster.get("ranged_attack")
    if melee and melee.get("type", -1) >= 0:
        return (melee["range"] * CM_PER_WU, proj_damage(melee), False, 0.0)
    if ranged and ranged.get("type", -1) >= 0:
        p = projectiles[ranged["type"]]
        speed_cms = p["speed"] * CM_PER_WU * TICKS_PER_SECOND
        return (ranged["range"] * CM_PER_WU, proj_damage(ranged), True, speed_cms)
    return (0.0, 0.0, False, 0.0)


def build():
    with open(PHYSICS, encoding="utf-8") as fh:
        phys = json.load(fh)
    monsters = phys["monsters"]
    projectiles = phys["projectiles"]
    type_counts = used_monster_types()

    manifest = {}
    rows = []          # for M1MonsterTable.h
    import_list = []   # for ue5_import_sprites.py
    skipped = {}

    for mtype in sorted(type_counts):
        mon = monsters[mtype]
        coll = mon["collection"] & 31
        clut = mon["collection"] >> 5
        coll_data = load_collection(coll)
        if coll_data is None:
            skipped[mtype] = "collection Coll_%02d missing on disk" % coll
            continue
        if mon["radius"] <= 0.0 or mon["height"] <= 0.0:
            skipped[mtype] = "degenerate def (radius/height 0; placeholder slot)"
            continue

        states = {}
        states["stationary"] = resolve_state(coll_data, coll, mon.get("stationary_shape"))
        states["moving"] = resolve_state(coll_data, coll, mon.get("moving_shape"))
        states["hit"] = resolve_state(coll_data, coll, mon.get("hit_shape"))
        # Hard variants first (the canonical violent death look), soft as fallback.
        states["dying"] = (resolve_state(coll_data, coll, mon.get("hard_dying_shape"))
                           or resolve_state(coll_data, coll, mon.get("soft_dying_shape")))
        states["dead"] = (resolve_state(coll_data, coll, mon.get("hard_dead_shape"))
                          or resolve_state(coll_data, coll, mon.get("soft_dead_shape")))

        if not states["moving"] and not states["stationary"]:
            skipped[mtype] = "no usable stationary/moving shapes"
            continue

        # Sprite picks (front view): stand, move frames, dead -- with fallbacks.
        stand_frame = ((states["stationary"] or states["moving"])["frames"][0])
        move = states["moving"] or states["stationary"]
        move_frames = move["frames"]
        if states["dead"]:
            dead_frame = states["dead"]["frames"][0]
        elif states["dying"]:
            dead_frame = states["dying"]["frames"][-1]  # last dying frame = on the ground
        else:
            dead_frame = stand_frame

        # Death cry: the dying animation's frame sound, else the random sound.
        death_sound_id = states["dying"]["frame_sound"] if states["dying"] else -1
        death_sound = sound_path(death_sound_id) or sound_path(mon.get("random_sound", -1))

        base = "T_mon%d" % mtype
        import_list.append({"png_path": stand_frame["png"], "asset_name": base + "_stand"})
        for i, fr in enumerate(move_frames):
            import_list.append({"png_path": fr["png"], "asset_name": "%s_move%d" % (base, i)})
        import_list.append({"png_path": dead_frame["png"], "asset_name": base + "_dead"})

        # Stats (units per the module docstring).
        rng_cm, dmg, is_ranged, rng_speed = attack_info(mon, projectiles)
        size_frame = move_frames[0]
        name = MONSTER_NAMES.get(mtype, "Mon%02d" % mtype)
        row = {
            "type": mtype,
            "name": name,
            "vitality": float(max(1, mon["vitality"])),  # lookers/civs have 0
            "radius_cm": round(mon["radius"] * CM_PER_WU, 2),
            "height_cm": round(mon["height"] * CM_PER_WU, 2),
            "speed_cms": round(mon["speed"] / 1024.0 * 100.0 * TICKS_PER_SECOND, 2),
            "visual_range_cm": round(mon["visual_range"] * CM_PER_WU, 2),
            "attack_range_cm": round(rng_cm, 2),
            "attack_interval_s": round(max(0.25, mon["attack_frequency"] / TICKS_PER_SECOND), 4),
            "attack_damage": round(dmg, 2),
            "ranged": is_ranged,
            "ranged_speed_cms": round(rng_speed, 2),
            "activation_sound": sound_path(mon.get("activation_sound", -1)),
            "random_sound": sound_path(mon.get("random_sound", -1)),
            "death_sound": death_sound,
            "sprite_base": "/Game/Sprites/Monsters/" + base,
            "move_frames": len(move_frames),
            "move_frame_time_s": round(max(1, move["ticks_per_frame"]) / TICKS_PER_SECOND, 4),
            "sprite_width_cm": size_frame["width_cm"],
            "sprite_height_cm": size_frame["height_cm"],
        }
        rows.append(row)
        manifest[str(mtype)] = {
            "name": name,
            "collection": coll,
            "clut": clut,
            "placement_count": type_counts[mtype],
            "states": states,
            "row": row,
        }

    return rows, manifest, import_list, skipped, type_counts


# ---------------------------------------------------------------------------
# Spawn table

def build_spawns(usable_types):
    levels = []  # (level_name, [spawn, ...]) sorted by filename
    dropped = 0
    for f in sorted(glob.glob(os.path.join(GEO, "*_placements.json"))):
        stem = os.path.basename(f)[:-len("_placements.json")]
        if not re.match(r"^\d{2}_", stem):
            continue  # debug rooms / look variants (ARR_*, TEST_*) are not cooked
        level_name = "L_" + _safe(stem)
        with open(f, encoding="utf-8") as fh:
            d = json.load(fh)
        spawns = []
        for o in d["objects"]:
            if o["type"] != 0:
                continue
            if o["object_index"] not in usable_types:
                dropped += 1
                continue
            spawns.append((o["object_index"], o["x"], o["y"], o["z"], o["facing_deg"]))
        levels.append((level_name, spawns))
    return levels, dropped


# ---------------------------------------------------------------------------
# C++ emit

def fmt_f(v):
    return ("%.2f" % float(v)) + "f"


def write_monster_table(rows):
    lines = [GENERATED_NOTE]
    lines.append("#pragma once\n")
    lines.append('#include "CoreMinimal.h"\n')
    lines.append("/** One Marathon 1 monster type (stats in UE cm / seconds; see")
    lines.append(" *  Tools/gen_monster_assets.py for the unit conversions). Sounds are full")
    lines.append(" *  asset paths or empty. SpriteBase is the /Game/Sprites/Monsters texture")
    lines.append(" *  prefix; the import script provides _stand, _move0..N-1 and _dead. */")
    lines.append("struct FM1MonsterRow")
    lines.append("{")
    lines.append("\tint32 Type;")
    lines.append("\tconst TCHAR* Name;")
    lines.append("\tfloat Vitality;")
    lines.append("\tfloat RadiusCm;")
    lines.append("\tfloat HeightCm;")
    lines.append("\tfloat SpeedCmS;")
    lines.append("\tfloat VisualRangeCm;")
    lines.append("\tfloat AttackRangeCm;")
    lines.append("\tfloat AttackIntervalS;")
    lines.append("\tfloat AttackDamage;")
    lines.append("\tbool bRangedAttack;")
    lines.append("\tfloat RangedSpeedCmS;")
    lines.append("\tconst TCHAR* ActivationSound;")
    lines.append("\tconst TCHAR* RandomSound;")
    lines.append("\tconst TCHAR* DeathSound;")
    lines.append("\tconst TCHAR* SpriteBase;")
    lines.append("\tint32 MoveFrames;")
    lines.append("\tfloat MoveFrameTimeS;")
    lines.append("\tfloat SpriteWidthCm;")
    lines.append("\tfloat SpriteHeightCm;")
    lines.append("};\n")
    lines.append("static const FM1MonsterRow GM1MonsterTable[] =")
    lines.append("{")
    for r in rows:
        lines.append(
            "\t{ %d, TEXT(\"%s\"), %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, TEXT(\"%s\"), TEXT(\"%s\"), TEXT(\"%s\"), TEXT(\"%s\"), %d, %s, %s, %s },"
            % (r["type"], r["name"], fmt_f(r["vitality"]), fmt_f(r["radius_cm"]),
               fmt_f(r["height_cm"]), fmt_f(r["speed_cms"]), fmt_f(r["visual_range_cm"]),
               fmt_f(r["attack_range_cm"]), fmt_f(r["attack_interval_s"]),
               fmt_f(r["attack_damage"]), "true" if r["ranged"] else "false",
               fmt_f(r["ranged_speed_cms"]), r["activation_sound"], r["random_sound"],
               r["death_sound"],
               r["sprite_base"], r["move_frames"], fmt_f(r["move_frame_time_s"]),
               fmt_f(r["sprite_width_cm"]), fmt_f(r["sprite_height_cm"])))
    lines.append("};\n")
    lines.append("static const int32 GM1MonsterTableCount = UE_ARRAY_COUNT(GM1MonsterTable);\n")
    # static (not inline): the table above has internal linkage, so an inline
    # function referencing it would be an ODR trap across TUs.
    lines.append("static const FM1MonsterRow* M1FindMonster(int32 Type)")
    lines.append("{")
    lines.append("\tfor (const FM1MonsterRow& Row : GM1MonsterTable)")
    lines.append("\t{")
    lines.append("\t\tif (Row.Type == Type)")
    lines.append("\t\t{")
    lines.append("\t\t\treturn &Row;")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn nullptr;")
    lines.append("}")
    path = os.path.join(SRC, "M1MonsterTable.h")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def write_spawn_table(levels):
    lines = [GENERATED_NOTE]
    lines.append("#pragma once\n")
    lines.append('#include "CoreMinimal.h"')
    lines.append('#include "Containers/ArrayView.h"\n')
    lines.append("/** One monster placement: type + UE world cm (Z may be floor-relative --")
    lines.append(" *  the spawner snaps to the floor) + facing in UE yaw degrees. */")
    lines.append("struct FM1MonsterSpawn")
    lines.append("{")
    lines.append("\tint32 MonsterType;")
    lines.append("\tfloat X;")
    lines.append("\tfloat Y;")
    lines.append("\tfloat Z;")
    lines.append("\tfloat FacingDeg;")
    lines.append("};\n")
    lines.append("struct FM1LevelSpawns")
    lines.append("{")
    lines.append("\tconst TCHAR* LevelName;  // cooked short map name, e.g. L_00_Arrival")
    lines.append("\tconst FM1MonsterSpawn* Spawns;")
    lines.append("\tint32 Count;")
    lines.append("};\n")
    for level_name, spawns in levels:
        lines.append("static const FM1MonsterSpawn GM1Spawns_%s[] =" % level_name)
        lines.append("{")
        if spawns:
            for t, x, y, z, deg in spawns:
                lines.append("\t{ %d, %s, %s, %s, %s }," % (
                    t, fmt_f(x), fmt_f(y), fmt_f(z), fmt_f(deg)))
        else:
            lines.append("\t{ -1, 0.00f, 0.00f, 0.00f, 0.00f },  // no monsters; keep array non-empty")
        lines.append("};\n")
    lines.append("static const FM1LevelSpawns GM1LevelSpawnTable[] =")
    lines.append("{")
    for level_name, spawns in levels:
        lines.append("\t{ TEXT(\"%s\"), GM1Spawns_%s, %d }," % (
            level_name, level_name, len(spawns)))
    lines.append("};\n")
    lines.append("static const int32 GM1LevelSpawnTableCount = UE_ARRAY_COUNT(GM1LevelSpawnTable);\n")
    # Runtime map names carry prefixes (UEDPIE_0_L_00_Arrival), so match by
    # "contains". Level stems are already space-free + _safe()-normalized, the
    # same normalization the cooked map packages use. static, not inline: the
    # tables above have internal linkage (see M1MonsterTable.h note).
    lines.append("static TArrayView<const FM1MonsterSpawn> M1SpawnsForLevel(const FString& MapName)")
    lines.append("{")
    lines.append("\tfor (const FM1LevelSpawns& Level : GM1LevelSpawnTable)")
    lines.append("\t{")
    lines.append("\t\tif (MapName.Contains(Level.LevelName, ESearchCase::IgnoreCase))")
    lines.append("\t\t{")
    lines.append("\t\t\treturn TArrayView<const FM1MonsterSpawn>(Level.Spawns, Level.Count);")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn TArrayView<const FM1MonsterSpawn>();")
    lines.append("}")
    path = os.path.join(SRC, "M1SpawnTable.h")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


# ---------------------------------------------------------------------------

def main():
    rows, manifest, import_list, skipped, type_counts = build()
    usable = set(r["type"] for r in rows)
    levels, dropped = build_spawns(usable)

    os.makedirs(SPRITES_OUT, exist_ok=True)
    manifest_path = os.path.join(SPRITES_OUT, "monsters_manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as fh:
        json.dump({"monsters": manifest, "skipped": skipped}, fh, indent=1, sort_keys=True)
    import_path = os.path.join(SPRITES_OUT, "import_list.json")
    with open(import_path, "w", encoding="utf-8") as fh:
        json.dump(import_list, fh, indent=1)

    table_path = write_monster_table(rows)
    spawn_path = write_spawn_table(levels)

    total_spawns = sum(len(s) for _, s in levels)
    print("monster types in placements : %d (%d monsters)"
          % (len(type_counts), sum(type_counts.values())))
    print("usable monster types        : %d" % len(rows))
    for t, why in sorted(skipped.items()):
        print("  skipped type %2d (x%d): %s" % (t, type_counts[t], why))
    print("sprite imports              : %d" % len(import_list))
    print("levels                      : %d, spawn rows %d (dropped %d unusable)"
          % (len(levels), total_spawns, dropped))
    print("wrote:")
    for p in (manifest_path, import_path, table_path, spawn_path):
        print("  " + p)
    print("\nsample rows:")
    for r in rows[:4] + [r for r in rows if r["type"] in (18, 22, 30)]:
        print("  type %2d %-28s vit %-6.0f r %5.1fcm h %5.1fcm spd %5.0fcm/s "
              "dmg %5.1f %s sprite %4.1fx%4.1fcm"
              % (r["type"], r["name"], r["vitality"], r["radius_cm"], r["height_cm"],
                 r["speed_cms"], r["attack_damage"],
                 "RNG" if r["ranged"] else "MEL",
                 r["sprite_width_cm"], r["sprite_height_cm"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
