"""Generate the Marathon 1 enemy data tables + sprite import lists.

Plain Python (no UE). Reads the extracted reference data:

    Reference/Physics/physics.json            monster + projectile defs
    Reference/Shapes/Coll_<NN>/shapes.json     high/low shapes + bitmap PNGs
    Reference/Geometry/<NN>_<Name>_placements.json   monster placements (UE cm)
    Tools/m1_sound_names.json                  'snd ' resource id -> canonical name

and writes:

    Reference/Sprites/monsters_manifest.json   per-type state -> frames (debug/qa)
    Reference/Sprites/import_list.json         png -> T_mon<N>_* for ue5_import_sprites.py
    Source/M1UE5/M1MonsterTable.h              GENERATED monster stat rows
    Source/M1UE5/M1SpawnTable.h                GENERATED per-level spawn lists

Units (verified against the extracted data):
  - physics radius/height/visual_range/attack range are floats in World Units
    (1 WU = 1024 internal = 100 UE cm)            -> cm = v * 100
  - monster `speed` is an int in internal-units/tick -> cm/s = v / 1024 * 100 * 30
  - projectile `speed` is a float in WU/tick         -> cm/s = v * 100 * 30
  - shapes world_left/right/top/bottom are ints in internal units -> cm = v/1024*100
  - attack_frequency / ticks_per_frame are 30Hz ticks -> s = v / 30

Monster identities come from Aleph One's M1 monster class bits
(`monster_definitions.h`: _class_*_m1) cross-checked against the high_shape
names embedded in each collection ("hulk.walk", "Madd.idle", "minion.idle"...).

Run:  python Tools/gen_monster_assets.py
"""
