"""Generate M1LightTable.h -- Marathon LITE lights as per-room point lights.

Marathon lighting is a per-surface light LEVEL, not a 3D light: every polygon
names a `floor_light` and `ceiling_light` index into the level's LITE array
(intensity 0..1, plus mode/type/period for on-off + animation). A single LITE
record is a shared *channel* referenced by many polygons.

To get room-by-room mood (and switchable lights) in UE5 without spawning one
light per polygon (up to 255 -> a dynamic-light storm), we GROUP polygons:
connected polygons (via POLY.adjacent_polys) that share the same floor_light are
unioned into one region, and we emit ONE movable point light per region at the
region's centroid, mid-height between floor and ceiling. The light carries its
LiteIndex so a light switch (panel_type 4 -> Kind 5, Target = LITE index) can
toggle every light on that channel. v1 keys off floor_light (== ceiling_light on
~80% of polys); ceiling-only lights are a follow-up.

Run:  C:\\m1-ue5\\.venv\\Scripts\\python.exe Tools/gen_light_assets.py

Position uses the SAME frame as the other generators: S=100/1024 cm per Marathon
unit, X=center_x*S, Y=center_y*S (no sign flip -- matches gen_panel_assets).
"""
import glob
import os
import re
import json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPS = os.path.join(ROOT, "Reference", "Maps")
OUT = os.path.join(ROOT, "Source", "M1UE5", "M1LightTable.h")

S = 100.0 / 1024.0

# Region radius bounds (cm) and the margin added beyond the farthest member.
RADIUS_MIN = 350.0
RADIUS_MAX = 2600.0
RADIUS_MARGIN = 450.0
# Lights dimmer than this (on-level intensity 0..1) aren't worth spawning.
MIN_INTENSITY = 0.03


def safe(stem):
    return re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_")


class UnionFind:
    def __init__(self, n):
        self.p = list(range(n))

    def find(self, a):
        while self.p[a] != a:
            self.p[a] = self.p[self.p[a]]
            a = self.p[a]
        return a

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[ra] = rb


def lights_for_level(data):
    polys = data.get("POLY") or []
    lite = data.get("LITE") or []
    n = len(polys)
    if n == 0 or not lite:
        return []

    # Union connected polygons that share the same floor_light channel.
    uf = UnionFind(n)
    for i, p in enumerate(polys):
        fl = p.get("floor_light", -1)
        for nb in p.get("adjacent_polys", []) or []:
            if 0 <= nb < n and polys[nb].get("floor_light", -2) == fl:
                uf.union(i, nb)

    # Gather members per region root.
    regions = {}
    for i, p in enumerate(polys):
        fl = p.get("floor_light", -1)
        if not (0 <= fl < len(lite)):
            continue
        regions.setdefault(uf.find(i), []).append(i)

    out = []
    for members in regions.values():
        p0 = polys[members[0]]
        idx = p0.get("floor_light", -1)
        if not (0 <= idx < len(lite)):
            continue
        L = lite[idx]
        # On-level brightness: prefer max_intensity, fall back to the current
        # intensity scalar when the bounds are zeroed (constant lights).
        on = L.get("max_intensity", 0.0) or L.get("intensity", 0.0)
        if on < MIN_INTENSITY:
            continue
        cxs = [polys[m].get("center_x", 0) for m in members]
        cys = [polys[m].get("center_y", 0) for m in members]
        cx = sum(cxs) / len(cxs)
        cy = sum(cys) / len(cys)
        mid = sum((polys[m].get("floor_height", 0) + polys[m].get("ceiling_height", 0)) / 2.0
                  for m in members) / len(members)
        # Region radius = farthest member center from the centroid + margin.
        far = max(((px - cx) ** 2 + (py - cy) ** 2) ** 0.5 for px, py in zip(cxs, cys))
        radius = max(RADIUS_MIN, min(RADIUS_MAX, far * S + RADIUS_MARGIN))
        out.append({
            "x": round(cx * S, 2),
            "y": round(cy * S, 2),
            "z": round(mid * S, 2),
            "radius": round(radius, 1),
            "intensity": round(float(on), 3),
            "lite": idx,
            "mode": int(L.get("mode", 1)),  # 1 = on, 3 = off (initial state)
        })
    # Stable order for reproducible headers.
    out.sort(key=lambda d: (d["lite"], d["x"], d["y"]))
    return out


def main():
    files = sorted(f for f in glob.glob(os.path.join(MAPS, "*.json"))
                   if not f.endswith("manifest.json"))
    levels = []
    total = 0
    for f in files:
        d = json.load(open(f, encoding="utf-8"))
        stem = safe(os.path.splitext(os.path.basename(f))[0])
        lights = lights_for_level(d.get("data", {}))
        total += len(lights)
        levels.append(("L_" + stem, lights))

    lines = [
        "// GENERATED by Tools/gen_light_assets.py -- do not hand-edit.",
        "// Regenerate with:  python Tools/gen_light_assets.py",
        "",
        "#pragma once",
        "",
        "#include \"CoreMinimal.h\"",
        "#include \"Containers/ArrayView.h\"",
        "",
        "/** One Marathon LITE light, grouped to a connected same-channel region.",
        " *  X/Y/Z = region centroid at mid-height (cm). Radius = attenuation (cm).",
        " *  Intensity = on-level brightness 0..1 (scaled to candela by AM1Light).",
        " *  LiteIndex = the LITE channel (a light switch toggles by this).",
        " *  Mode = initial state (1 = on, 3 = off). */",
        "struct FM1Light",
        "{",
        "\tfloat X, Y, Z, Radius, Intensity;",
        "\tint32 LiteIndex, Mode;",
        "};",
        "",
        "struct FM1LevelLights",
        "{",
        "\tconst TCHAR* LevelName;",
        "\tconst FM1Light* Lights;",
        "\tint32 Count;",
        "};",
        "",
    ]
    for level_name, lights in levels:
        lines.append("static const FM1Light GM1Lights_%s[] =" % level_name)
        lines.append("{")
        for p in lights:
            lines.append("\t{ %.2ff, %.2ff, %.2ff, %.1ff, %.3ff, %d, %d },"
                         % (p["x"], p["y"], p["z"], p["radius"], p["intensity"],
                            p["lite"], p["mode"]))
        if not lights:
            lines.append("\t{ 0.00f, 0.00f, 0.00f, 0.0f, 0.0f, -1, 0 },  // none")
        lines.append("};")
        lines.append("")

    lines.append("static const FM1LevelLights GM1LevelLightTable[] =")
    lines.append("{")
    for level_name, lights in levels:
        lines.append("\t{ TEXT(\"%s\"), GM1Lights_%s, %d },"
                     % (level_name, level_name, len(lights)))
    lines.append("};")
    lines.append("")
    lines.append("static const int32 GM1LevelLightTableCount = UE_ARRAY_COUNT(GM1LevelLightTable);")
    lines.append("")
    lines.append("static TArrayView<const FM1Light> M1LightsForLevel(const FString& MapName)")
    lines.append("{")
    lines.append("\tfor (const FM1LevelLights& Level : GM1LevelLightTable)")
    lines.append("\t{")
    lines.append("\t\tif (MapName.Contains(Level.LevelName, ESearchCase::IgnoreCase))")
    lines.append("\t\t{")
    lines.append("\t\t\treturn TArrayView<const FM1Light>(Level.Lights, Level.Count);")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn TArrayView<const FM1Light>();")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote %s" % OUT)
    print("%d region-lights across %d levels (avg %.1f/level, max %d)"
          % (total, len(levels), total / max(1, len(levels)),
             max(len(l) for _, l in levels)))


if __name__ == "__main__":
    main()
