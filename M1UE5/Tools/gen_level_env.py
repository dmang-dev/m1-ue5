"""Generate the per-level environment table (music track + vacuum flag).

Reads each level's Minf chunk from Map.scen:
  - song_index       -> which of the 16 music tracks plays (canonical M1 mapping;
                        AM1GameMode::PlayLevelMusic uses it instead of guessing)
  - environment_flags bit 0 (0x1) = VACUUM -> the suit oxygen drains here
                        (AM1Character vacuum O2 drain). Only L08 "G4 Sunbathing"
                        is vacuum in M1.

Maps level_index -> cooked short name (L_<NN>_...) via the geometry placement
filenames, exactly like gen_terminal_assets.py, so names match the cooked maps.

    python Tools/gen_level_env.py   ->  Source/M1UE5/M1LevelEnvTable.h
"""
import glob
import os
import re
import sys

from marathon_utils import macbinary, wad, maps

import m1_paths

ROOT = str(m1_paths.PROJECT)
GEO = os.path.join(ROOT, "Reference", "Geometry")
SRC = os.path.join(ROOT, "Source", "M1UE5")
MAP_SCEN = str(m1_paths.MAP_SCEN)

NOTE = ("// GENERATED by Tools/gen_level_env.py -- do not hand-edit.\n"
        "// Regenerate with:  python Tools/gen_level_env.py\n")


def _safe(stem):
    return re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_")


def level_names():
    names = {}
    for f in sorted(glob.glob(os.path.join(GEO, "*_placements.json"))):
        stem = os.path.basename(f)[:-len("_placements.json")]
        m = re.match(r"^(\d{2})_", stem)
        if m:
            names.setdefault(int(m.group(1)), "L_" + _safe(stem))
    return names


def build():
    names = level_names()
    blob = open(MAP_SCEN, "rb").read()
    data, rsrc, _ = macbinary.unwrap(blob)
    payload = data if data is not None else blob
    hdr = wad.read_header(payload)
    directory = wad.read_directory(payload, hdr)

    rows = []
    for idx, entry in enumerate(directory):
        name = names.get(idx)
        if name is None:
            continue  # debug / look variants are not cooked campaign levels
        mi = maps.parse_level(payload, entry, hdr)["data"]["Minf"]
        song = int(mi.get("song_index", -1))
        vac = bool(int(mi.get("environment_flags", 0)) & 0x1)
        rows.append((name, song, vac))
    return rows


def main():
    rows = build()
    out = [NOTE, "#pragma once\n", '#include "CoreMinimal.h"',
           '#include "Containers/ArrayView.h"\n',
           "/** Per-level environment: which music track (song_index, 0-15; -1 = none)",
           " *  and whether the level is VACUUM (suit oxygen drains). From Map.scen Minf. */",
           "struct FM1LevelEnv", "{", "\tconst TCHAR* MapName;", "\tint32 SongIndex;",
           "\tbool bVacuum;", "};\n",
           "static const FM1LevelEnv GM1LevelEnv[] =", "{"]
    for name, song, vac in rows:
        out.append("\t{ TEXT(\"%s\"), %d, %s }," % (name, song, "true" if vac else "false"))
    out.append("};\n")
    out.append("static const int32 GM1LevelEnvCount = UE_ARRAY_COUNT(GM1LevelEnv);\n")
    out.append("// Runtime map names are prefixed (UEDPIE_0_L_00_Arrival); match by Contains.")
    out.append("static const FM1LevelEnv* M1LevelEnvForMap(const FString& MapName)")
    out.append("{")
    out.append("\tfor (const FM1LevelEnv& E : GM1LevelEnv)")
    out.append("\t{")
    out.append("\t\tif (MapName.Contains(E.MapName, ESearchCase::IgnoreCase))")
    out.append("\t\t{")
    out.append("\t\t\treturn &E;")
    out.append("\t\t}")
    out.append("\t}")
    out.append("\treturn nullptr;  // not a campaign level (test/experimental map)")
    out.append("}")
    path = os.path.join(SRC, "M1LevelEnvTable.h")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    vac_levels = [n for n, s, v in rows if v]
    print("levels: %d ; vacuum: %s" % (len(rows), vac_levels))
    print("wrote " + path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
