# C++ emit

def fmt_f(v):
    return ("%.2f" % float(v)) + "f"


def write_terminal_table(levels):
    lines = [GENERATED_NOTE]
    lines.append("#pragma once\n")
    lines.append('#include "CoreMinimal.h"')
    lines.append('#include "Containers/ArrayView.h"\n')
    lines.append("/** One Marathon terminal placement: UE world cm of the wall panel")
    lines.append(" *  (Z is eye-ish height on the wall) + the terminal art id and how many")
    lines.append(" *  pages it has. Page texture at runtime: /Game/UI/Terminals/T_term<id>_p<page>. */")
    lines.append("struct FM1Terminal")
    lines.append("{")
    lines.append("\tfloat X;")
    lines.append("\tfloat Y;")
    lines.append("\tfloat Z;")
    lines.append("\tint32 TermId;")
    lines.append("\tint32 PageCount;")
    lines.append("};\n")
    lines.append("struct FM1LevelTerminals")
    lines.append("{")
    lines.append("\tconst TCHAR* LevelName;  // cooked short map name, e.g. L_00_Arrival")
    lines.append("\tconst FM1Terminal* Terminals;")
    lines.append("\tint32 Count;")
    lines.append("};\n")

    for level_name, rows in levels:
        lines.append("static const FM1Terminal GM1Terminals_%s[] =" % level_name)
        lines.append("{")
        if rows:
            for r in rows:
                lines.append("\t{ %s, %s, %s, %d, %d }," % (
                    fmt_f(r["x"]), fmt_f(r["y"]), fmt_f(r["z"]),
                    r["term_id"], r["pages"]))
        else:
            lines.append("\t{ 0.00f, 0.00f, 0.00f, -1, 0 },  // no terminals; keep array non-empty")
        lines.append("};\n")

    lines.append("static const FM1LevelTerminals GM1LevelTerminalTable[] =")
    lines.append("{")
    for level_name, rows in levels:
        lines.append("\t{ TEXT(\"%s\"), GM1Terminals_%s, %d }," % (
            level_name, level_name, len(rows)))
    lines.append("};\n")
    lines.append("static const int32 GM1LevelTerminalTableCount = UE_ARRAY_COUNT(GM1LevelTerminalTable);\n")
    # Runtime map names carry prefixes (UEDPIE_0_L_00_Arrival), so match by
    # "contains" -- the same normalization M1SpawnTable uses. static, not inline:
    # the tables above have internal linkage (header-only static const).
    lines.append("static TArrayView<const FM1Terminal> M1TerminalsForLevel(const FString& MapName)")
    lines.append("{")
    lines.append("\tfor (const FM1LevelTerminals& Level : GM1LevelTerminalTable)")
    lines.append("\t{")
    lines.append("\t\tif (MapName.Contains(Level.LevelName, ESearchCase::IgnoreCase))")
    lines.append("\t\t{")
    lines.append("\t\t\treturn TArrayView<const FM1Terminal>(Level.Terminals, Level.Count);")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn TArrayView<const FM1Terminal>();")
    lines.append("}")
    path = os.path.join(SRC, "M1TerminalTable.h")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def main():
    levels, import_list, skipped, total_terms = build()

    os.makedirs(TERM_DIR, exist_ok=True)
    import_path = os.path.join(TERM_DIR, "term_import_list.json")
    with open(import_path, "w", encoding="utf-8") as fh:
        json.dump(import_list, fh, indent=1)

    table_path = write_terminal_table(levels)

    levels_with_terms = sum(1 for _, r in levels if r)
    print("levels                  : %d (%d with terminals)" % (len(levels), levels_with_terms))
    print("terminals placed        : %d" % total_terms)
    print("unique pages to import  : %d" % len(import_list))
    print("skipped (id, no pages)  : %d" % len(skipped))
    for li, tid, why in skipped:
        print("  L%02d term %d: %s" % (li, tid, why))
    print("wrote:")
    print("  " + import_path)
    print("  " + table_path)
    print("\nsample placements:")
    shown = 0
    for level_name, rows in levels:
        for r in rows:
            print("  %-28s term %d  %d pages  (%.0f, %.0f, %.0f)cm"
                  % (level_name, r["term_id"], r["pages"], r["x"], r["y"], r["z"]))
            shown += 1
            if shown >= 8:
                return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
