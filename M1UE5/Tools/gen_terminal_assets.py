"""Generate the Marathon 1 terminal (lore) placement table + page import list.

Plain Python on the project venv (needs marathon_utils). Reads the original
M1 map directly for terminal *locations* (the green-on-black page art is
ALREADY rendered to Reference/Terminals/appl_term<id>_p<page>.png -- we do not
re-render text here) and writes:

    Reference/Terminals/term_import_list.json   unique pages to import as
                                                T_term<id>_p<page>
    Source/M1UE5/M1TerminalTable.h              GENERATED per-level placement
                                                rows (UE cm) + lookup helper

Terminal id formula (verified):  id = 1000 + level_index*10 + panel_perm
  level_index is the Map.scen directory order (0 = Arrival), matching our
  L_<NN>_... level naming. panel_perm 9 is the conventional "unfinished"
  terminal.  Page count for a terminal = number of appl_term<id>_p<N>.png on
  disk; ids with zero pages are skipped (some perms have no rendered terminal).

Coordinate transform to UE cm (MUST match the sector geometry + placements):
    S = 100/1024 ; mesh_fy = +1 (geometry pipeline flips y, OBJ importer flips
    again -> net +1, same as Tools/scen_to_obj.py _placements):
        X_cm = x * S
        Y_cm = y * S * mesh_fy
        Z_cm = floor_height * S + 55   (eye-ish height on the wall)
x,y are the terminal line's MIDPOINT in Marathon map units (int16, 1/1024 WU).

Run:  C:\\m1-ue5\\.venv\\Scripts\\python.exe Tools\\gen_terminal_assets.py
"""
import glob
import json
import os
import re
import sys

from marathon_utils import macbinary, wad, maps, terminals

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, "Reference")
TERM_DIR = os.path.join(REF, "Terminals")
GEO = os.path.join(REF, "Geometry")
SRC = os.path.join(ROOT, "Source", "M1UE5")
MAP_SCEN = r"C:\m1-ue5\M1SOURCE\Marathon-20250829\Map.scen"

S = 100.0 / 1024.0      # Marathon internal unit -> UE cm
MESH_FY = 1.0           # net y sign after the geometry/OBJ double-flip
EYE_Z_CM = 55.0         # terminal panel height above the floor

GENERATED_NOTE = (
    "// GENERATED by Tools/gen_terminal_assets.py -- do not hand-edit.\n"
    "// Regenerate with:  python Tools/gen_terminal_assets.py\n")


def _safe(stem):
    """UE-safe asset name -- MUST match ue5_headless_build.py::_safe exactly."""
    return re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_")


def level_names():
    """level_index -> cooked short level name (L_<NN>_...), from the geometry
    placement filenames (the same source the spawn table uses), so the names
    line up exactly with the cooked maps. Falls back to a synthesized name if a
    placement file is missing for some index."""
    names = {}
    for f in sorted(glob.glob(os.path.join(GEO, "*_placements.json"))):
        stem = os.path.basename(f)[:-len("_placements.json")]
        m = re.match(r"^(\d{2})_", stem)
        if not m:
            continue  # debug rooms / look variants are not cooked
        names[int(m.group(1))] = "L_" + _safe(stem)
    return names


def page_count(term_id):
    """Number of appl_term<id>_p<N>.png pages on disk for this terminal id."""
    n = 0
    while os.path.isfile(os.path.join(TERM_DIR, "appl_term%d_p%d.png" % (term_id, n))):
        n += 1
    return n


def line_floor_map(lvl):
    """Build line_index -> floor_height (Marathon units). The terminal location's
    own `poly` field can be out of range in the M1 data; the line's owner polys
    (cw_poly/ccw_poly), or the polygons that list the line, give the real floor."""
    poly = lvl["data"]["POLY"]
    lins = lvl["data"]["LINS"]
    # Fallback index: every polygon that references a given line.
    line2poly = {}
    for pi, p in enumerate(poly):
        for L in p.get("lines", []):
            line2poly.setdefault(L, []).append(pi)

    def floor_for_line(line_idx):
        if not (0 <= line_idx < len(lins)):
            return None
        ln = lins[line_idx]
        for key in ("cw_poly", "ccw_poly"):
            pp = ln.get(key, -1)
            if pp is not None and 0 <= pp < len(poly):
                return poly[pp]["floor_height"]
        for pp in line2poly.get(line_idx, []):
            if 0 <= pp < len(poly):
                return poly[pp]["floor_height"]
        return None

    return floor_for_line


def build():
    names = level_names()

    blob = open(MAP_SCEN, "rb").read()
    data, rsrc, _ = macbinary.unwrap(blob)
    payload = data if data is not None else blob
    hdr = wad.read_header(payload)
    directory = wad.read_directory(payload, hdr)

    levels = []        # (level_name, [term, ...]) -- term = dict for the C++ row
    import_set = {}     # asset_name -> abs png path (dedupe across all levels)
    skipped = []        # (level_index, term_id, reason)
    total_terms = 0

    for level_index, entry in enumerate(directory):
        level_name = names.get(level_index)
        if level_name is None:
            # No cooked geometry for this index (debug/look variants excluded);
            # still synthesize a name so the lookup never misses a real level.
            level_name = "L_%02d" % level_index
        lvl = maps.parse_level(payload, entry, hdr)
        floor_for_line = line_floor_map(lvl)
        locs = terminals.terminal_locations(lvl, is_m1=True)

        rows = []
        for loc in locs:
            term_id = 1000 + level_index * 10 + loc["panel_perm"]
            pages = page_count(term_id)
            if pages == 0:
                skipped.append((level_index, term_id, "no pages on disk"))
                continue
            floor = floor_for_line(loc["line"])
            if floor is None:
                floor = 0  # unresolved floor: place at level origin height
            x_cm = loc["x"] * S
            y_cm = loc["y"] * S * MESH_FY
            z_cm = floor * S + EYE_Z_CM
            rows.append({
                "x": x_cm, "y": y_cm, "z": z_cm,
                "term_id": term_id, "pages": pages,
            })
            total_terms += 1
            for page in range(pages):
                asset = "T_term%d_p%d" % (term_id, page)
                import_set[asset] = os.path.join(
                    TERM_DIR, "appl_term%d_p%d.png" % (term_id, page))

        levels.append((level_name, rows))

    import_list = [{"png_path": png, "asset_name": name}
                   for name, png in sorted(import_set.items())]
    return levels, import_list, skipped, total_terms


